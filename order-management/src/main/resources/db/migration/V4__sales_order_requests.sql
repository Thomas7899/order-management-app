-- Auftragseingang: Bestellungen per E-Mail oder PDF, die ausgelesen und in Kundenaufträge übernommen werden
create table sales_order_request_files (
    id bigint generated by default as identity,
    file_name varchar(255) not null,
    content_type varchar(100) not null,
    content bytea not null,
    primary key (id)
);

create table sales_order_requests (
    id bigint generated by default as identity,
    request_number varchar(10) not null unique,
    status varchar(20) not null check (status in ('OPEN','CONVERTED','REJECTED')),
    source_type varchar(10) not null check (source_type in ('EMAIL','PDF','TEXT')),
    sender varchar(200),
    subject varchar(300),
    source_text text not null,
    file_id bigint references sales_order_request_files (id),
    received_at timestamp(6) not null,
    extraction text,
    extraction_source varchar(10),
    extracted_at timestamp(6),
    order_id bigint references orders (id),
    rejection_note varchar(500),
    processed_at timestamp(6),
    processed_by varchar(50),
    created_by varchar(50),
    primary key (id)
);

create index idx_sales_order_requests_status on sales_order_requests (status, received_at desc);

alter table number_ranges drop constraint if exists number_ranges_range_object_check;
alter table number_ranges add constraint number_ranges_range_object_check
    check (range_object in ('SALES_ORDER','DELIVERY','INVOICE','MATERIAL_DOCUMENT','CUSTOMER','MATERIAL','SALES_ORDER_REQUEST'));

-- Basisschema der Order-Management-App (SAP-naher Order-to-Cash-Prozess).
-- Erzeugt aus dem JPA-Modell (PostgreSQL-Dialekt) und um Indizes ergänzt.
-- Weitere Änderungen bitte als neue Migration V2__..., V3__... anlegen, nie diese Datei ändern.

create extension if not exists vector;

create table change_documents (
    changed_at timestamp(6) not null,
    id bigint generated by default as identity,
    object_id bigint not null,
    change_type varchar(10) not null check (change_type in ('INSERT','UPDATE','DELETE','EVENT')),
    object_class varchar(30) not null check (object_class in ('SALES_ORDER','DELIVERY','INVOICE','CUSTOMER','MATERIAL','MATERIAL_DOCUMENT')),
    object_number varchar(30),
    field_name varchar(60),
    changed_by varchar(100) not null,
    description varchar(500),
    new_value varchar(500),
    old_value varchar(500),
    primary key (id)
);

create table customers (
    active boolean not null,
    credit_limit numeric(12,2),
    discount_percent numeric(5,2),
    payment_terms varchar(4) check (payment_terms in ('ZB01','ZB30','ZB14','ZB00')),
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    customer_number varchar(10) unique,
    address varchar(255),
    city varchar(255),
    country varchar(255),
    email varchar(255) not null unique,
    first_name varchar(255) not null,
    last_name varchar(255) not null,
    phone varchar(255),
    zip_code varchar(255),
    primary key (id)
);

create table deliveries (
    delivery_type varchar(4) not null,
    planned_goods_issue_date date not null,
    created_at timestamp(6) not null,
    customer_id bigint not null,
    goods_issue_date timestamp(6),
    id bigint generated by default as identity,
    order_id bigint not null,
    version bigint,
    warehouse_id bigint not null,
    delivery_number varchar(10) not null unique,
    goods_issue_document varchar(10),
    billing_status varchar(20) not null check (billing_status in ('NOT_RELEVANT','NOT_PROCESSED','PARTIALLY_PROCESSED','FULLY_PROCESSED')),
    status varchar(20) not null check (status in ('CREATED','GOODS_ISSUED','CANCELLED')),
    created_by varchar(100),
    shipping_address varchar(500),
    primary key (id)
);

create table delivery_items (
    item_number integer not null,
    quantity integer not null,
    delivery_id bigint not null,
    id bigint generated by default as identity,
    order_item_id bigint not null,
    product_id bigint not null,
    primary key (id)
);

create table invoice_items (
    cost_amount numeric(12,2) not null,
    gross_amount numeric(12,2) not null,
    item_number integer not null,
    net_amount numeric(12,2) not null,
    quantity integer not null,
    tax_amount numeric(12,2) not null,
    tax_rate numeric(5,2) not null,
    unit_net_price numeric(12,4) not null,
    delivery_item_id bigint,
    id bigint generated by default as identity,
    invoice_id bigint not null,
    order_item_id bigint not null,
    product_id bigint not null,
    primary key (id)
);

create table invoices (
    billing_date date not null,
    billing_type varchar(2) not null check (billing_type in ('F2','S1')),
    cash_discount_amount numeric(12,2),
    cash_discount_date date,
    cash_discount_percent numeric(5,2),
    cost_amount numeric(12,2) not null,
    currency varchar(3) not null,
    due_date date,
    gross_amount numeric(12,2) not null,
    net_amount numeric(12,2) not null,
    paid_amount numeric(12,2),
    paid_at date,
    payment_terms varchar(4) check (payment_terms in ('ZB01','ZB30','ZB14','ZB00')),
    tax_amount numeric(12,2) not null,
    created_at timestamp(6) not null,
    customer_id bigint not null,
    delivery_id bigint,
    id bigint generated by default as identity,
    order_id bigint not null,
    reference_invoice_id bigint,
    version bigint,
    invoice_number varchar(10) not null unique,
    status varchar(20) not null check (status in ('OPEN','PAID','CANCELLED')),
    created_by varchar(100),
    primary key (id)
);

create table number_ranges (
    current_number bigint,
    from_number bigint not null,
    to_number bigint not null,
    range_object varchar(30) not null check (range_object in ('SALES_ORDER','DELIVERY','INVOICE','MATERIAL_DOCUMENT','CUSTOMER','MATERIAL')),
    primary key (range_object)
);

create table order_item_conditions (
    condition_type varchar(4) not null,
    condition_value numeric(12,2) not null,
    rate numeric(12,2) not null,
    rate_unit varchar(3) not null,
    statistical boolean not null,
    step_number integer not null,
    id bigint generated by default as identity,
    order_item_id bigint not null,
    description varchar(60) not null,
    primary key (id)
);

create table order_items (
    billed_quantity integer not null,
    confirmed_quantity integer not null,
    delivered_quantity integer not null,
    gross_amount numeric(12,2) not null,
    item_discount_percent numeric(5,2),
    item_number integer not null,
    net_amount numeric(12,2) not null,
    quantity integer not null,
    rejection_reason varchar(4) check (rejection_reason in ('R01','R02','R03','R04','R05','R10')),
    tax_amount numeric(12,2) not null,
    tax_rate numeric(5,2) not null,
    unit_price numeric(10,2) not null,
    id bigint generated by default as identity,
    order_id bigint not null,
    product_id bigint not null,
    primary key (id)
);

create table orders (
    currency varchar(3) not null,
    net_amount numeric(12,2) not null,
    order_type varchar(4) not null,
    payment_terms varchar(4) check (payment_terms in ('ZB01','ZB30','ZB14','ZB00')),
    requested_delivery_date date,
    tax_amount numeric(12,2) not null,
    total_amount numeric(12,2) not null,
    created_at timestamp(6),
    customer_id bigint not null,
    id bigint generated by default as identity,
    order_date timestamp(6) not null,
    updated_at timestamp(6),
    version bigint,
    order_number varchar(10) not null unique,
    billing_status varchar(20) not null check (billing_status in ('NOT_RELEVANT','NOT_PROCESSED','PARTIALLY_PROCESSED','FULLY_PROCESSED')),
    credit_status varchar(20) not null check (credit_status in ('NOT_CHECKED','APPROVED','BLOCKED','RELEASED')),
    delivery_status varchar(20) not null check (delivery_status in ('NOT_RELEVANT','NOT_PROCESSED','PARTIALLY_PROCESSED','FULLY_PROCESSED')),
    status varchar(20) not null check (status in ('OPEN','IN_PROCESS','COMPLETED','CANCELLED')),
    customer_reference varchar(35),
    created_by varchar(100),
    billing_address varchar(500),
    shipping_address varchar(500),
    notes TEXT,
    primary key (id)
);

create table product_reviews (
    rating integer not null,
    created_at timestamp(6) not null,
    customer_id bigint not null,
    id bigint generated by default as identity,
    order_item_id bigint,
    product_id bigint not null,
    comment TEXT,
    primary key (id)
);

create table products (
    active boolean not null,
    cost_price numeric(10,2),
    price numeric(10,2) not null,
    stock_quantity integer not null,
    unit_of_measure varchar(3) not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    tax_code varchar(10) not null check (tax_code in ('FULL','REDUCED','EXEMPT')),
    material_number varchar(18) unique,
    description varchar(1000),
    category varchar(255),
    image_url varchar(255),
    name varchar(255) not null,
    primary key (id)
);

create table review_embeddings (
    id bigint generated by default as identity,
    review_id bigint not null unique,
    updated_at timestamp(6),
    content_hash varchar(64),
    source_text TEXT,
    embedding vector(1536),
    primary key (id)
);

create table review_trend_reports (
    window_end date,
    window_start date,
    generated_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    summary varchar(2000),
    negative_trends jsonb,
    neutral_observations jsonb,
    positive_trends jsonb,
    primary key (id)
);

create table stock_movements (
    document_item integer not null,
    movement_code varchar(3) not null,
    quantity integer not null,
    quantity_after integer,
    quantity_before integer,
    reversed boolean not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    posting_date timestamp(6) not null,
    product_id bigint not null,
    reversed_movement_id bigint,
    source_warehouse_id bigint,
    target_warehouse_id bigint,
    movement_number varchar(10) not null,
    reference_type varchar(20) check (reference_type in ('ORDER','DELIVERY','PURCHASE_ORDER','RETURN_ORDER','INVENTORY','MANUAL')),
    movement_type varchar(30) not null check (movement_type in ('INITIAL_ENTRY','GOODS_RECEIPT','GOODS_ISSUE','DELIVERY_ISSUE','TRANSFER','INVENTORY_ADJUSTMENT','RETURN','SCRAP')),
    reference_number varchar(35),
    created_by varchar(100),
    reason varchar(255),
    primary key (id),
    constraint uk_stock_movements_document_item unique (movement_number, document_item)
);

create table user_roles (
    user_id bigint not null,
    role varchar(20) not null check (role in ('SALES','WAREHOUSE','BILLING','CONTROLLING','ADMIN')),
    primary key (user_id, role)
);

create table users (
    active boolean not null,
    demo_account boolean not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    last_login_at timestamp(6),
    username varchar(12) not null unique,
    full_name varchar(100) not null,
    password_hash varchar(100) not null,
    email varchar(255) not null unique,
    primary key (id)
);

create table warehouse_stocks (
    max_stock integer not null,
    min_stock integer not null,
    quantity integer not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    last_counted_at timestamp(6),
    product_id bigint not null,
    updated_at timestamp(6),
    warehouse_id bigint not null,
    bin_location varchar(255),
    primary key (id),
    unique (warehouse_id, product_id)
);

create table warehouses (
    active boolean not null,
    is_default boolean not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    address varchar(255),
    city varchar(255),
    code varchar(255) not null unique,
    country varchar(255),
    description varchar(255),
    name varchar(255) not null,
    zip_code varchar(255),
    primary key (id)
);

